const CADENCE_UNITS: readonly { seconds: number; label: string }[] = [
  { seconds: 604800, label: "week" },
  { seconds: 86400, label: "day" },
  { seconds: 3600, label: "hour" },
  { seconds: 60, label: "minute" },
];

function pluralize(count: number, unit: string): string {
  if (count === 1) return `1 ${unit}`;
  const plural = unit.endsWith("s") ? `${unit}es` : `${unit}s`;
  return `${count} ${plural}`;
}

export function formatCadenceInterval(seconds: number): string {
  for (const unit of CADENCE_UNITS) {
    if (seconds < unit.seconds) continue;
    return pluralize(Math.round(seconds / unit.seconds), unit.label);
  }
  return `${Math.round(seconds)}s`;
}

export function cadenceText(cadence: RecurringCadence): string {
  if (cadence.kind === "manual") {
    return `Manual only — ${cadence.detail}`;
  }
  if (cadence.kind === "rides_on") {
    return `Rides on ${cadence.rides_on ?? "another process"} — ${cadence.detail}`;
  }
  if (cadence.interval_seconds != null) {
    return `Every ${formatCadenceInterval(cadence.interval_seconds)}`;
  }
  if (cadence.cron_expression != null) {
    return `Cron \`${cadence.cron_expression}\` — ${cadence.detail}`;
  }
  return cadence.detail;
}

export function lastRunText(process: RecurringProcess): string {
  if (process.last_run.at == null) {
    return `Never observed — ${process.last_run.provenance.detail || "no run recorded yet"}`;
  }
  return formatRelativeTime(process.last_run.at);
}

const OUTCOME_TEXT: Record<RecurringRunState, string> = {
  succeeded: "Succeeded",
  failed: "Failed",
  attention: "Needs a person",
  cancelled: "Ended without completing",
  in_progress: "Currently running",
  queued: "Queued to run",
  never_ran: "Never run yet",
  unknown: "Outcome unknown",
};

export function outcomeText(process: RecurringProcess): string {
  if (process.last_run.state === "attention" && process.last_run.outcome === "degraded") {
    return "Completed with degradation";
  }
  return OUTCOME_TEXT[process.last_run.state];
}

function notApplicableReason(process: RecurringProcess): string {
  if (process.process_id === "daily_digest") {
    return "it is generated by the triage sweep, not run on its own";
  }
  return "this kind of process exposes no run duration to measure";
}

export function durationText(process: RecurringProcess): string {
  if (process.duration_state === "measured") {
    return process.duration_seconds != null ? formatActiveDuration(process.duration_seconds) : "—";
  }
  if (process.duration_state === "not_applicable") {
    return `Not applicable — ${notApplicableReason(process)}`;
  }
  return `Unknown — ${process.last_run.provenance.detail || "duration not recorded"}`;
}

export function overdueTone(state: RecurringOverdueState): ChipTone {
  if (state === "overdue") return "transitional";
  if (state === "on_time") return "green";
  return "unknown";
}

const RUN_STATE_TONE: Record<RecurringRunState, ChipTone> = {
  succeeded: "green",
  failed: "red",
  attention: "transitional",
  cancelled: "unknown",
  in_progress: "unknown",
  queued: "unknown",
  never_ran: "unknown",
  unknown: "unknown",
};

const RUN_STATE_LABEL: Record<RecurringRunState, string> = {
  succeeded: "Succeeded",
  failed: "Failed",
  attention: "Needs attention",
  cancelled: "Cancelled",
  in_progress: "Running",
  queued: "Queued",
  never_ran: "Never run",
  unknown: "Unknown",
};

export function runStateTone(state: RecurringRunState): ChipTone {
  return RUN_STATE_TONE[state];
}

export function runStateText(state: RecurringRunState): string {
  return RUN_STATE_LABEL[state];
}

const OVERDUE_LABEL: Record<RecurringOverdueState, string> = {
  overdue: "Overdue",
  on_time: "On time",
  unknown: "Unknown",
};

export function overdueText(process: RecurringProcess): string {
  return `${OVERDUE_LABEL[process.overdue.state]} — ${process.overdue.detail}`;
}

export interface RecurringRow {
  readonly processId: string;
  readonly label: string;
  readonly cadenceText: string;
  readonly lastRunText: string;
  readonly outcomeText: string;
  readonly durationText: string;
  readonly overdueText: string;
  readonly overdueTone: ChipTone;
  readonly overdueState: RecurringOverdueState;
  readonly runState: RecurringRunState;
  readonly runStateTone: ChipTone;
  readonly runStateText: string;
  readonly destination: RecurringDestination;
  readonly subRows: readonly RecurringRow[];
}

export function toRecurringRow(process: RecurringProcess, engineKey: string): RecurringRow {
  return {
    processId: process.process_id,
    label: process.label,
    cadenceText: cadenceText(process.cadence),
    lastRunText: lastRunText(process),
    outcomeText: outcomeText(process),
    durationText: durationText(process),
    overdueText: overdueText(process),
    overdueTone: overdueTone(process.overdue.state),
    overdueState: process.overdue.state,
    runState: process.last_run.state,
    runStateTone: runStateTone(process.last_run.state),
    runStateText: runStateText(process.last_run.state),
    destination: processDestination(process, engineKey),
    subRows: process.sub_steps.map((sub) => toRecurringRow(sub, engineKey)),
  };
}

export function recurringRows(status: RecurringStatus, engineKey: string): RecurringRow[] {
  return status.processes.map((process) => toRecurringRow(process, engineKey));
}

export interface RecurringSummaryCounts {
  readonly total: number;
  readonly overdue: number;
  readonly failed: number;
  readonly attention: number;
}

function flattenRows(rows: readonly RecurringRow[]): readonly RecurringRow[] {
  return rows.flatMap((row) => [row, ...flattenRows(row.subRows)]);
}

export function failingRows(rows: readonly RecurringRow[]): readonly RecurringRow[] {
  return flattenRows(rows).filter((row) => row.runState === "failed");
}

export function summaryCounts(rows: readonly RecurringRow[]): RecurringSummaryCounts {
  const flat = flattenRows(rows);
  const failed = flat.filter((row) => row.runState === "failed").length;
  const attentionOnly = flat.filter((row) => row.runState === "attention").length;
  return {
    total: flat.length,
    overdue: flat.filter((row) => row.overdueState === "overdue").length,
    failed,
    attention: failed + attentionOnly,
  };
}

export function summaryLine(counts: RecurringSummaryCounts): string {
  const parts = [pluralize(counts.total, "process")];
  if (counts.overdue > 0) parts.push(`${counts.overdue} overdue`);
  if (counts.attention > 0) parts.push(`${counts.attention} need attention`);
  return parts.join(" · ");
}

const MAX_NAMED_FAILURES = 3;

export function mergedSummaryLine(counts: RecurringSummaryCounts, rows: readonly RecurringRow[]): string {
  const base = summaryLine(counts);
  const failing = failingRows(rows);
  if (failing.length === 0) return base;
  const shown = failing.slice(0, MAX_NAMED_FAILURES).map((row) => row.label);
  const extra = failing.length - shown.length;
  const failingClause = extra > 0 ? `${shown.join(", ")} +${String(extra)} more` : shown.join(", ");
  return `${base} · Failing: ${failingClause}`;
}

export function backupCoverageText(coverage: RecurringBackupCoverage): string {
  if (coverage.included_in_last_snapshot === true) {
    const changed = coverage.changed_since_count;
    const changedSuffix =
      changed == null ? " · changes since unknown" : ` · ${pluralize(changed, "change")} since`;
    return `Covered by the most recent backup snapshot${changedSuffix}. ${coverage.excluded_caveat}.`;
  }
  if (coverage.included_in_last_snapshot === false) {
    return `Not covered by the most recent backup — ${coverage.provenance.detail}. ${coverage.excluded_caveat}.`;
  }
  return `Backup coverage unknown — ${coverage.provenance.detail}. ${coverage.excluded_caveat}.`;
}
