import { useCallback, useState } from "react";

import DescribedButton from "../../../components/DescribedButton";
import { errorMessageOf } from "../../../lib/errorMessage";
import { useStickyInstruction } from "../hooks/useStickyInstruction";
import ErrorBanner from "../../../ui/ErrorBanner";

const ORIGIN_SUFFIX: Record<"dispatch" | "generated", string> = {
  dispatch: "typed for a prior dispatch",
  generated: "generated by the system",
};

const CLEAR_DESCRIPTION =
  "Stops this instruction from applying to future automatically-routed runs. It cannot be restored.";

export interface StickyInstructionCardProps {
  readonly taskId: string;
  readonly onCleared: () => void;
}

export default function StickyInstructionCard({
  taskId,
  onCleared,
}: Readonly<StickyInstructionCardProps>) {
  const { text, origin, error, clear } = useStickyInstruction(taskId);
  const [clearing, setClearing] = useState(false);
  const [clearError, setClearError] = useState<string | null>(null);

  const handleClear = useCallback(() => {
    setClearing(true);
    setClearError(null);
    clear().then(
      () => {
        setClearing(false);
        onCleared();
      },
      (err: unknown) => {
        setClearing(false);
        setClearError(errorMessageOf(err));
      },
    );
  }, [clear, onCleared]);

  if (text === null) {
    if (error === null) return null;
    return (
      <ErrorBanner data-testid="sticky-instruction-error">
        Could not load the persisted dispatch instruction — {error}
      </ErrorBanner>
    );
  }

  return (
    <section
      data-testid="sticky-instruction-card"
      className="rounded-md border border-border bg-surface-elevated p-2 text-xs"
    >
      <p className="mb-2 text-text-muted">
        Persisted instruction — applies to every automatically-routed run of
        this task until replaced or cleared.
        {origin !== null && (
          <span data-testid="sticky-instruction-origin"> ({ORIGIN_SUFFIX[origin]})</span>
        )}
      </p>
      <p data-testid="sticky-instruction-text" className="whitespace-pre-wrap text-text-primary">
        {text}
      </p>
      <div className="mt-2">
        <DescribedButton
          variant="ghost"
          label={clearing ? "Clearing…" : "Clear"}
          ariaLabel={clearing ? "Clearing instruction…" : "Clear instruction"}
          description={CLEAR_DESCRIPTION}
          testId="sticky-instruction-clear"
          onClick={handleClear}
          busy={clearing}
        />
      </div>
      {clearError !== null && (
        <div className="mt-2">
          <ErrorBanner data-testid="sticky-instruction-clear-error">
            Clear failed — {clearError}
          </ErrorBanner>
        </div>
      )}
    </section>
  );
}
