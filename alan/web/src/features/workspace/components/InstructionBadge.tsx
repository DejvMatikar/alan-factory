import type {
  DispatchInstructionsReadback,
  DispatchInstructionsStatus,
  InstructionOrigin,
} from "../../../api";
import Disclosure from "../../../ui/Disclosure";

const STATUS_LABELS: Record<DispatchInstructionsStatus, string> = {
  attached: "instructions attached",
  none: "no instructions",
  not_delivered: "instructions not delivered",
  unknown: "instructions unknown",
};

const STATUS_STYLES: Record<DispatchInstructionsStatus, string> = {
  attached: "bg-status-active-tint/15 text-status-active-fg",
  none: "bg-status-neutral-tint/15 text-status-neutral-fg",
  not_delivered: "bg-status-attention-tint/15 text-status-attention-fg",
  unknown: "bg-status-neutral-tint/15 text-status-neutral-fg",
};

const NOT_DELIVERED_EXPLANATION =
  "This team's worker prompt does not carry dispatch instructions.";

const ORIGIN_SUFFIX: Record<InstructionOrigin, string> = {
  dispatch: "typed for this run",
  inherited: "persisted from a prior dispatch",
  generated: "generated by the system",
};

function Pill({
  status,
  testId,
}: Readonly<{ status: DispatchInstructionsStatus; testId: string }>) {
  return (
    <span
      className={`inline-block rounded px-2 py-0.5 text-xs ${STATUS_STYLES[status]}`}
      data-testid={testId}
    >
      {STATUS_LABELS[status]}
    </span>
  );
}

export interface InstructionBadgeProps {
  invId: string;
  readback: DispatchInstructionsReadback;
  showDetails?: boolean;
}

export default function InstructionBadge({
  invId,
  readback,
  showDetails = true,
}: Readonly<InstructionBadgeProps>) {
  const testId = `instruction-badge-${invId}`;
  const pill = <Pill status={readback.status} testId={testId} />;
  const hasText = readback.text != null && readback.text.length > 0;

  if (!showDetails || !hasText) {
    return pill;
  }

  return (
    <Disclosure
      preset="badge"
      defaultOpen={false}
      testId={`${testId}-details`}
      label={pill}
    >
      <div
        className="mt-1 max-h-64 max-w-md overflow-y-auto rounded-md border border-border bg-surface-elevated p-2 text-xs text-text-primary"
        data-testid={`${testId}-text`}
      >
        {readback.status === "not_delivered" && (
          <p className="mb-2 text-text-muted" data-testid={`${testId}-not-delivered-note`}>
            {NOT_DELIVERED_EXPLANATION}
          </p>
        )}
        {readback.status === "attached" && readback.origin != null && (
          <p className="mb-2 text-text-muted" data-testid={`${testId}-origin`}>
            ({ORIGIN_SUFFIX[readback.origin]})
          </p>
        )}
        <p className="whitespace-pre-wrap">{readback.text}</p>
      </div>
    </Disclosure>
  );
}
