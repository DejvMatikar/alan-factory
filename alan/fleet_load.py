from __future__ import annotations

import os

FLEET_NICE_DELTA = 10
FLEET_PYTEST_WORKER_CAP = 2
FLEET_VITEST_WORKER_CAP = 2
FLEET_BASH_DEFAULT_TIMEOUT_MS = 1_800_000
FLEET_BASH_MAX_TIMEOUT_MS = 1_800_000
FLEET_BASH_MAX_OUTPUT_LENGTH = 150_000
FLEET_ASYNC_STALL_TIMEOUT_MS = 1_800_000
FLEET_IDLE_TIMEOUT_SECONDS = 2100.0
FLEET_LOAD_THRESHOLD_MULTIPLIER = 2.0

_PYTEST_ADDOPTS_ENV = "PYTEST_ADDOPTS"
_VITEST_MAX_WORKERS_ENV = "VITEST_MAX_WORKERS"
_BASH_DEFAULT_TIMEOUT_MS_ENV = "BASH_DEFAULT_TIMEOUT_MS"
_BASH_MAX_TIMEOUT_MS_ENV = "BASH_MAX_TIMEOUT_MS"
_BASH_MAX_OUTPUT_LENGTH_ENV = "BASH_MAX_OUTPUT_LENGTH"
_ASYNC_STALL_TIMEOUT_MS_ENV = "CLAUDE_ASYNC_AGENT_STALL_TIMEOUT_MS"
_PYTHONDONTWRITEBYTECODE_ENV = "PYTHONDONTWRITEBYTECODE"


def apply_fleet_priority(pid: int) -> None:
    os.setpriority(os.PRIO_PROCESS, pid, FLEET_NICE_DELTA)


def fleet_env(env: dict[str, str]) -> dict[str, str]:
    result = dict(env)
    existing = result.get(_PYTEST_ADDOPTS_ENV, "")
    result[_PYTEST_ADDOPTS_ENV] = f"-n {FLEET_PYTEST_WORKER_CAP} {existing}".strip()
    result[_VITEST_MAX_WORKERS_ENV] = str(FLEET_VITEST_WORKER_CAP)
    result[_BASH_DEFAULT_TIMEOUT_MS_ENV] = str(FLEET_BASH_DEFAULT_TIMEOUT_MS)
    result[_BASH_MAX_TIMEOUT_MS_ENV] = str(FLEET_BASH_MAX_TIMEOUT_MS)
    result[_BASH_MAX_OUTPUT_LENGTH_ENV] = str(FLEET_BASH_MAX_OUTPUT_LENGTH)
    result[_ASYNC_STALL_TIMEOUT_MS_ENV] = str(FLEET_ASYNC_STALL_TIMEOUT_MS)
    result[_PYTHONDONTWRITEBYTECODE_ENV] = "1"
    return result


def host_cores() -> int:
    return os.cpu_count() or 1


def load_threshold() -> float:
    return host_cores() * FLEET_LOAD_THRESHOLD_MULTIPLIER


def read_load1() -> float:
    return os.getloadavg()[0]
